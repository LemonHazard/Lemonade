-- VSCode integration (Linux only for now).
--
-- After `premake5 gmake`, writes into the workspace's .vscode folder:
--   - tasks.json:  "premake: generate", "build: <project> (<config>)" for every project
--                  and configuration, and "clean" if the script defines that action;
--   - launch.json: a gdb debug configuration for every runnable project and config.
-- Both are regenerated on every run, so edits to them are lost; they only depend on
-- the workspace, so a game that includes the engine gets them for its own projects.
--
-- settings.json and extensions.json belong to the user: they are only created when
-- missing, and settings.json only gets the compile_commands.json path added if it
-- doesn't set one.
--
-- Usage from premake5.lua:
--   dofile("tools/vscode.lua")

local vscode = {}

local COMPILE_COMMANDS = "compile_commands.json" -- written by tools/unity.lua

--------------------------------------------------------------------------------------
-- JSON: objects are { __object = { { key, value }, ... } } to keep the key order.
--------------------------------------------------------------------------------------

local function object(pairs)
    return { __object = pairs }
end

local function quote(s)
    return '"' .. s:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"'
end

local function encode(value, indent)
    indent = indent or 0
    local pad   = string.rep("    ", indent + 1)
    local close = string.rep("    ", indent)

    if type(value) == "string" then
        return quote(value)
    elseif type(value) ~= "table" then
        return tostring(value)
    end

    local items = {}
    if value.__object then
        for _, pair in ipairs(value.__object) do
            table.insert(items, pad .. quote(pair[1]) .. ": " .. encode(pair[2], indent + 1))
        end
        if #items == 0 then return "{}" end
        return "{\n" .. table.concat(items, ",\n") .. "\n" .. close .. "}"
    end

    for _, item in ipairs(value) do
        table.insert(items, pad .. encode(item, indent + 1))
    end
    if #items == 0 then return "[]" end
    return "[\n" .. table.concat(items, ",\n") .. "\n" .. close .. "]"
end

local function write(file_path, content, base_dir)
    os.mkdir(path.getdirectory(file_path))
    local result = os.writefile_ifnotequal(content, file_path)
    if result < 0 then
        error("vscode: could not write " .. file_path, 0)
    end
    if result > 0 then
        print("vscode: generated " .. path.getrelative(base_dir, file_path))
    end
end

local HEADER = "// Generated by tools/vscode.lua on `premake5 gmake`, do not edit.\n"

--------------------------------------------------------------------------------------
-- Generators
--------------------------------------------------------------------------------------

-- Path as written in a .vscode file: relative to the workspace folder when inside it.
local function workspace_path(wks, p)
    local relative = path.getrelative(wks.location, p)
    if relative == "." then return "${workspaceFolder}" end
    if path.isabsolute(relative) or relative:startswith("..") then return p end
    return "${workspaceFolder}/" .. relative
end

local function build_label(prj, cfg)
    return "build: " .. prj.name .. " (" .. cfg.shortname .. ")"
end

local function generate_command(wks)
    local premake_path = path.getrelative(wks.location, _PREMAKE_COMMAND)
    if path.isabsolute(premake_path) or premake_path:startswith("..") then
        premake_path = '"' .. _PREMAKE_COMMAND .. '"'
    else
        premake_path = "./" .. premake_path
    end

    local command = premake_path
    local script = path.getrelative(wks.location, _MAIN_SCRIPT)
    if script ~= "premake5.lua" then
        command = command .. ' --file="' .. script .. '"'
    end
    return command
end

local function tasks_json(wks)
    local premake_command = generate_command(wks)
    local cwd = object { { "cwd", "${workspaceFolder}" } }

    local tasks = {
        object {
            { "label",          "premake: generate" },
            { "detail",         "Regenerate makefiles, unity files and VSCode files" },
            { "type",           "shell" },
            { "command",        premake_command .. " gmake" },
            { "options",        cwd },
            { "presentation",   object { { "reveal", "silent" } } },
            { "problemMatcher", {} },
        },
    }

    local default_set = false
    for prj in premake.workspace.eachproject(wks) do
        for cfg in premake.project.eachconfig(prj) do
            local is_default = not default_set and (wks.startproject == nil or wks.startproject == prj.name)
            default_set = default_set or is_default

            table.insert(tasks, object {
                { "label",          build_label(prj, cfg) },
                { "type",           "shell" },
                { "command",        "make " .. prj.name .. " config=" .. cfg.shortname },
                { "options",        cwd },
                { "dependsOn",      "premake: generate" },
                { "group",          is_default and object { { "kind", "build" }, { "isDefault", true } } or "build" },
                { "problemMatcher", "$gcc" },
            })
        end
    end

    if premake.action.get("clean") then
        table.insert(tasks, object {
            { "label",          "clean" },
            { "detail",         "Remove generated project files and build output" },
            { "type",           "shell" },
            { "command",        premake_command .. " clean" },
            { "options",        cwd },
            { "problemMatcher", {} },
        })
    end

    return HEADER .. encode(object {
        { "version", "2.0.0" },
        { "tasks",   tasks },
    }) .. "\n"
end

local function launch_json(wks)
    local configurations = {}

    for prj in premake.workspace.eachproject(wks) do
        for cfg in premake.project.eachconfig(prj) do
            if cfg.kind == "ConsoleApp" or cfg.kind == "WindowedApp" then
                local environment = {}
                for _, env in ipairs(cfg.debugenvs or {}) do
                    local name, value = env:match("^([^=]+)=(.*)$")
                    if name then
                        table.insert(environment, object { { "name", name }, { "value", value } })
                    end
                end

                table.insert(configurations, object {
                    { "name",          prj.name .. " (" .. cfg.shortname .. ")" },
                    { "type",          "cppdbg" },
                    { "request",       "launch" },
                    { "program",       workspace_path(wks, cfg.buildtarget.abspath) },
                    { "args",          cfg.debugargs or {} },
                    { "cwd",           workspace_path(wks, cfg.debugdir or prj.location) },
                    { "environment",   environment },
                    { "preLaunchTask", build_label(prj, cfg) },
                    { "MIMode",        "gdb" },
                    { "setupCommands", {
                        object {
                            { "description",    "Enable pretty-printing" },
                            { "text",           "-enable-pretty-printing" },
                            { "ignoreFailures", true },
                        },
                    } },
                })
            end
        end
    end

    return HEADER .. encode(object {
        { "version",        "0.2.0" },
        { "configurations", configurations },
    }) .. "\n"
end

local function update_settings(wks, file_path)
    local key   = "C_Cpp.default.compileCommands"
    local value = workspace_path(wks, path.join(_MAIN_SCRIPT_DIR, COMPILE_COMMANDS))
    local entry = quote(key) .. ": " .. quote(value)

    local content = io.readfile(file_path)
    if not content or content:match("^%s*{%s*}%s*$") then
        write(file_path, "{\n    " .. entry .. "\n}\n", wks.location)
        return
    end

    if content:find(key, 1, true) then return end

    -- settings.json allows comments, so insert textually instead of parsing it.
    local open = content:find("{", 1, true)
    if not open then
        print("vscode: " .. file_path .. " has no top-level object, leaving it unchanged")
        return
    end
    local rest  = content:sub(open + 1)
    local empty = rest:match("^%s*}") ~= nil
    write(file_path, content:sub(1, open) .. "\n    " .. entry .. (empty and "\n" or ",") .. rest, wks.location)
end

local function create_extensions(wks, file_path)
    if os.isfile(file_path) then return end

    write(file_path, encode(object {
        { "recommendations", { "ms-vscode.cpptools" } },
    }) .. "\n", wks.location)
end

function vscode.generate()
    for wks in premake.global.eachWorkspace() do
        local dir = path.join(wks.location, ".vscode")

        write(path.join(dir, "tasks.json"),  tasks_json(wks),  wks.location)
        write(path.join(dir, "launch.json"), launch_json(wks), wks.location)
        update_settings(wks, path.join(dir, "settings.json"))
        create_extensions(wks, path.join(dir, "extensions.json"))
    end
end

premake.override(premake.main, "postAction", function(base)
    if os.istarget("linux") and (_ACTION == "gmake" or _ACTION == "gmake2") then
        vscode.generate()
    end
    base()
end)

return vscode
